-- ── 1. ขั้นไหนบ้างที่ยอมให้ push ────────────────────────────────────
--
-- เก็บเป็น "ชุดของขั้น" ไม่ใช่ค่าขั้นต่ำ เพราะขั้นที่มีค่ากับลูกค้าไม่ได้เรียงติดกัน
-- ร้านอยากได้ รับเข้าระบบ → นำจ่าย → สำเร็จ โดยข้ามช่วงขนส่งตรงกลาง
-- ซึ่งเกณฑ์แบบ ">= ขั้นต่ำ" เขียนไม่ได้
--
-- ต้องเป็นตัวเลข ไม่ใช่ข้อความ — Thai Post ส่ง status มาเป็นรหัสตัวเลข
-- ส่วนคำไทยที่คนอ่านออกอยู่ใน status_description คนละฟิลด์กัน
--
-- รหัสจริงตามที่ line-tacking/index.js:473-477 จดไว้จาก API (ไม่ใช่การเดา):
--   1  รับฝาก / รับเข้าระบบ
--   2  ระหว่างขนส่ง       ออกจากที่ทำการ · เข้าศูนย์คัดแยก — ยิงบ่อยสุด ทำอะไรไม่ได้
--   3  ออกไปนำจ่าย        ของอยู่กับบุรุษไปรษณีย์ ← ปลาเป็นต้องอยู่บ้านรับ
--   4  นำจ่ายไม่สำเร็จ     ปลาค้างที่ไปรษณีย์ — เพิ่มเข้าชุดได้ถ้าอยากได้
--   5  นำจ่ายสำเร็จ
--
-- ค่าเริ่มต้น {1,3,5} = นำเข้า · กำลังนำจ่าย · จัดส่งสำเร็จ (3 ข้อความ/พัสดุ)
-- บอทเทียบว่า "เปลี่ยนขั้น" ไม่ใช่ "ขั้นสูงขึ้น" ชุดนี้จึงเลือกข้ามขั้นกลางได้
