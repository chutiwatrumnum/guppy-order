-- แจ้งตอนนำจ่ายไม่สำเร็จ/ตีกลับด้วย (ขั้น 4)
--
-- ชุดเดิม {1,3,5} ครอบเฉพาะเส้นทางที่ทุกอย่างราบรื่น
-- แต่ขั้น 4 (4xx) คือตอนที่ปลาค้างอยู่ที่ไปรษณีย์ ไม่ได้อยู่กับลูกค้าและไม่ได้อยู่กับร้าน
-- เป็นจังหวะที่ต้องรีบตามที่สุดสำหรับของเป็น ๆ และนาน ๆ ทีถึงจะเกิด
-- จึงแทบไม่กินโควต้าเพิ่มเลย
update public.settings set parcel_push_tiers = array[1, 3, 4, 5];

-- คำใน cmd_help เดิมนับจำนวนไว้ ("3 จังหวะ") ซึ่งจะขัดกันเองพอมีครั้งที่ 4
-- เลิกนับ เปลี่ยนเป็นบอกว่าเกิดอะไรขึ้นบ้างแทน
-- replace หาไม่เจอก็ไม่ทำอะไร (ร้านแก้คำเองได้ตลอด)
update public.message_templates
set body = replace(
      body,
      'เด้งเตือนให้ 3 จังหวะ: รับเข้าระบบ · ออกไปนำจ่าย · ส่งถึง',
      E'เด้งเตือนให้ตอน: รับเข้าระบบ · ออกไปนำจ่าย · ส่งถึง\nถ้านำจ่ายไม่สำเร็จหรือตีกลับ จะแจ้งให้ทันทีเหมือนกันครับ'
    )
where key = 'cmd_help';
