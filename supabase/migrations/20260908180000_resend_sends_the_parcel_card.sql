-- "ส่งซ้ำ" ให้ส่งการ์ดสถานะพัสดุ ไม่ใช่ข้อความจัดส่งเต็ม ๆ อีกรอบ
--
-- ข้อความจัดส่งมีคำทักทาย เลขบิล คำอธิบายการแจ้งเตือน และคำเชิญชวนรีวิวของร้าน
-- พ่วงมาด้วย ซึ่งเหมาะกับตอนส่งครั้งแรก แต่ปุ่ม "ส่งซ้ำ" ใช้ตอนกู้เคสที่การติดตาม
-- หลุดไป — สิ่งที่อยากบอกคือ "ของอยู่ตรงนี้แล้ว" ไม่ใช่ทักทายใหม่ทั้งชุด
--
-- คิวเดิมส่งได้แค่ข้อความกับรูป เพราะการ์ดสร้างจากฝั่งบอท (ต้องดึงสถานะสด
-- จากไปรษณีย์ก่อน) หน้าแอดมินเป็นเบราว์เซอร์ จึงทำการ์ดเองไม่ได้
--
-- ใส่เลขพัสดุลงคิวแทน แล้วให้บอทเป็นคนไปดึงสถานะมาประกอบเป็นการ์ดตอนส่ง
-- ได้ผลพลอยได้คือการ์ดสดเสมอ ไม่ใช่ค่าที่แช่ไว้ตอนกดปุ่ม

alter table public.line_notifications
  add column if not exists tracking_number text;

comment on column public.line_notifications.tracking_number is
  'ใส่ไว้ = ให้บอทดึงสถานะพัสดุมาส่งเป็นการ์ดแทน message (message ใช้เป็นตัวสำรองเมื่อดึงไม่ได้)';

-- message ยังเป็น not null ต่อไปโดยตั้งใจ — เป็นตัวสำรองที่ต้องมีเสมอ
-- ไปรษณีย์ล่ม หรือเลขที่ยังไม่เข้าระบบ ต้องมีอะไรส่งให้ลูกค้าอยู่ดี
-- ดีกว่าเงียบหายไปเฉย ๆ ทั้งที่ร้านกดปุ่มไปแล้ว
