-- ── 2. ปิดข้อความรายตัวได้จากหน้าตั้งค่า ────────────────────────────
--
-- เดิมไม่มีสวิตช์ ถ้าอยากหยุดข้อความไหนต้องลบแถวทิ้ง ซึ่งไม่ได้ผล:
-- ทั้ง renderTemplate ฝั่งแอปและ render() ฝั่งบอทมี fallback ฝังไว้
-- พอหาแถวไม่เจอมันส่งคำเดิมออกไปอยู่ดี
alter table public.message_templates
  add column if not exists enabled boolean not null default true;

-- render_template ต้องเคารพสวิตช์ ไม่งั้นปิดแล้วยังส่งอยู่
-- คืน null เหมือนตอนหาแถวไม่เจอ ฝั่งเรียกเช็ก null อยู่แล้ว
create or replace function public.render_template(p_key text, p_vars jsonb default '{}'::jsonb)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  tpl text;
  k   text;
  v   text;
begin
  select body into tpl
  from public.message_templates
  where key = p_key and enabled;

  if tpl is null then
    return null;
  end if;

  for k, v in select key, value from jsonb_each_text(coalesce(p_vars, '{}'::jsonb)) loop
    tpl := replace(tpl, '{{' || k || '}}', coalesce(v, ''));
  end loop;

  return tpl;
end;
$$;

